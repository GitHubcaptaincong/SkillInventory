import { test, expect } from '@playwright/test'
import { existsSync, readFileSync } from 'node:fs'
const env=Object.fromEntries((existsSync('../.test-output/auth-smoke.env')?readFileSync('../.test-output/auth-smoke.env','utf8'):'').split(/\r?\n/).filter(x=>x.includes('=')).map(x=>{const i=x.indexOf('=');return [x.slice(0,i),x.slice(i+1)]}))
test('真实浏览器创建、预览、发布、草稿隔离、下架和删除', async ({ page, request }) => {
  const name = 'browser-' + Date.now()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('用户名').fill(process.env.E2E_ADMIN_USERNAME || env.ADMIN_USERNAME)
  await page.getByLabel('密码').fill(process.env.E2E_ADMIN_PASSWORD || env.ADMIN_INITIAL_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByRole('link', { name: '＋ 新建 Skill' })).toBeVisible()
  // External request context authenticates independently with a new read-only key.
  const csrf=await (await page.request.get('/api/auth/csrf')).json()
  const creation=await page.request.post('/api/admin/api-keys',{headers:{[csrf.headerName]:csrf.token},data:{name:'browser lifecycle'}})
  expect(creation.status()).toBe(201)
  const created=await creation.json()
  expect(typeof created.key==='string').toBe(true)
  const keyHeaders={'X-API-Key':created.key}

  await page.getByRole('link', { name: '＋ 新建 Skill' }).click()
  await page.getByLabel(/^name/).fill(name)
  await page.getByLabel(/^description/).fill('浏览器: 原始描述')
  await page.getByLabel('编辑草稿').fill('# 浏览器原文\n\n**安全预览**\n\n<img src=x onerror=alert(1)>')
  await expect(page.locator('.markdown strong')).toHaveText('安全预览')
  await expect(page.locator('.markdown img')).toHaveCount(0)
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page).toHaveURL(/\/skills\/\d+$/)
  await expect(page.getByText('草稿已保存，客户端发布内容未改变')).toBeVisible()
  expect((await request.get('/api/v1/skills/' + name,{headers:keyHeaders})).status()).toBe(404)
  await page.getByRole('button', { name: '发布已保存草稿' }).click()
  await expect(page.locator('.badge')).toHaveText('已发布')
  const original = await (await request.get('/api/v1/skills/' + name + '/SKILL.md',{headers:keyHeaders})).text()
  await page.getByLabel(/^description/).fill('浏览器: 未发布描述')
  await page.getByLabel('编辑草稿').fill('# 新正文')
  await page.getByRole('button', { name: '发布已保存草稿' }).click()
  await expect(page.getByRole('alert')).toContainText('请先保存草稿')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.locator('.badge')).toHaveText('有未发布修改')
  expect(await (await request.get('/api/v1/skills/' + name + '/SKILL.md',{headers:keyHeaders})).text()).toBe(original)
  await page.getByRole('button', { name: '当前发布快照', exact: true }).click()
  await expect(page.locator('.markdown h1')).toHaveText('浏览器原文')
  await page.screenshot({ path: '../.test-output/editor.png', fullPage: true })
  await page.getByRole('button', { name: '发布已保存草稿' }).click()
  await expect(page.locator('.badge')).toHaveText('已发布')
  expect(await (await request.get('/api/v1/skills/' + name + '/SKILL.md',{headers:keyHeaders})).text()).toContain('# 新正文')
  await page.getByRole('button', { name: '下架', exact: true }).click()
  await expect(page.locator('.badge')).toHaveText('未发布')
  expect((await request.get('/api/v1/skills/' + name,{headers:keyHeaders})).status()).toBe(404)
  await page.getByRole('link', { name: '← 返回列表' }).click()
  await page.getByLabel('搜索关键词').fill(name)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: name })
  await expect(row).toBeVisible()
  await page.screenshot({ path: '../.test-output/list.png', fullPage: true })
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByText('没有符合条件的 Skill。可以调整筛选或新建一个。')).toBeVisible()
  await page.request.post('/api/admin/api-keys/'+created.metadata.id+'/revoke',{headers:{[csrf.headerName]:csrf.token},data:{}})
  expect(errors).toEqual([])
})

test('Key 页面一次展示、关闭、撤销和退出',async({page})=>{
  page.on('dialog',dialog=>dialog.accept())
  await page.goto('/api-keys')
  await page.getByLabel('用户名').fill(process.env.E2E_ADMIN_USERNAME || env.ADMIN_USERNAME)
  await page.getByLabel('密码').fill(process.env.E2E_ADMIN_PASSWORD || env.ADMIN_INITIAL_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page).toHaveURL(/\/api-keys$/)
  const name='browser-key-'+Date.now()
  await page.getByLabel('名称').fill(name)
  await page.getByRole('button',{name:'创建 Key',exact:true}).click()
  await expect(page.getByText('完整 Key 只显示一次，请立即保存')).toBeVisible()
  const secret=await page.locator('p.code').textContent()
  expect(secret).toBeTruthy()
  await page.getByRole('button',{name:'关闭并清除'}).click()
  await expect(page.getByText('完整 Key 只显示一次，请立即保存')).toHaveCount(0)
  expect((await page.locator('body').textContent())!.includes(secret!)).toBe(false)
  const row=page.locator('section.card').filter({has:page.getByText(name,{exact:true})})
  await row.getByRole('button',{name:'撤销',exact:true}).click()
  await expect(row).toContainText('REVOKED')
  await page.getByRole('button',{name:'退出',exact:true}).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/admin/skills')).status()).toBe(401)
})
